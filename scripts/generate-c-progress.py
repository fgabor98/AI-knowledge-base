#!/usr/bin/env python3
"""Generate docs/c/progress.md, the C learning-progress checklist, from mkdocs.yml.

The checklist lists every page of the C section in navigation order, grouped
by chapter. docs/javascripts/c-progress.js turns each entry into a checkbox
and records visits in the reader's browser.

usage: generate-c-progress.py           write docs/c/progress.md
       generate-c-progress.py --check   fail if docs/c/progress.md is stale
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "c" / "progress.md"
SELF = "c/progress.md"


class NavLoader(yaml.SafeLoader):
    """SafeLoader that ignores mkdocs-specific tags such as !!python/name."""


NavLoader.add_multi_constructor("", lambda loader, suffix, node: None)
NavLoader.add_multi_constructor("tag:yaml.org,2002:python/", lambda loader, suffix, node: None)


def c_section(nav):
    for entry in nav:
        if isinstance(entry, dict) and "C" in entry:
            return entry["C"]
    raise SystemExit("mkdocs.yml: no top-level 'C' section in nav")


def pages(entries):
    """Yield (title, path) for every page in a nav subtree, in order."""
    for entry in entries:
        for title, value in entry.items():
            if isinstance(value, str):
                yield title, value
            else:
                yield from pages(value)


def link(path):
    return path[len("c/"):] if path.startswith("c/") else "../" + path


def render(section):
    lines = [
        "---",
        "status: draft",
        "reviewed: false",
        "domain: c",
        "difficulty: beginner",
        "last_reviewed: null",
        "---",
        "",
        "# C Learning Progress",
        "",
        "Tick a topic when you have learnt it. Opening a page marks it as *visited*",
        "automatically, so you can see what you have looked at but not yet worked through.",
        "",
        "Progress is stored in this browser only (local storage). Use **Export** to",
        "keep a backup or move it to another browser, and **Import** to restore it.",
        "",
        '<div id="c-progress-summary" class="c-progress-summary"></div>',
        "",
        "<!-- Generated by scripts/generate-c-progress.py from mkdocs.yml; do not edit by hand. -->",
        "",
    ]
    for entry in section:
        for title, value in entry.items():
            if isinstance(value, str):
                if value == SELF:
                    continue
                chapter, chapter_pages = "Start Here", [("C Programming " + title, value)]
            else:
                chapter = title
                chapter_pages = [(t, p) for t, p in pages(value) if p != SELF]
            if not chapter_pages:
                continue
            lines += [f"## {chapter}", "", '<div class="c-progress" markdown>', ""]
            for page_title, path in chapter_pages:
                label = "Overview" if page_title == chapter and path.endswith("index.md") else page_title
                lines.append(f"- [{label}]({link(path)})")
            lines += ["", "</div>", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    nav = yaml.load((ROOT / "mkdocs.yml").read_text(), Loader=NavLoader)["nav"]
    content = render(c_section(nav))
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print("docs/c/progress.md is out of date; run scripts/generate-c-progress.py",
                  file=sys.stderr)
            return 1
        print("docs/c/progress.md is up to date")
        return 0
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
